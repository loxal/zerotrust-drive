    fn user_stop_timeout(value: &'static str) -> FakeRunner {
        FakeRunner::new(move |argv, _| {
            if argv.starts_with("loginctl show-user") {
                ok("Linger=yes\n")
            } else if argv.starts_with("systemctl show user@") {
                ok(&format!("TimeoutStopUSec={value}\n"))
            } else {
                ok("")
            }
        })
    }

    #[test]
    fn service_systemd_install_explains_a_user_manager_stop_timeout_shorter_than_the_unit() {
        let dir = TestDir::new("service-systemd-user-timeout");
        let host = host(&dir, Platform::Linux);
        let def = encrypted(&host, Custody::SystemdCreds);
        // Ubuntu's systemd package ships user@.service.d/timeout.conf with 5 s.
        let lines = install_on(
            &host,
            &def,
            Path::new("/usr/bin/zdrive"),
            &user_stop_timeout("5s"),
        )
        .unwrap();
        let advice = lines
            .iter()
            .position(|line| line.contains("stops your user manager after 5 s"))
            .unwrap_or_else(|| panic!("{lines:?}"));
        assert!(lines[advice].contains("the next start uploads the rest"));
        assert_eq!(
            &lines[advice + 1..],
            [
                "sudo mkdir -p /etc/systemd/system/user@.service.d",
                "printf '[Service]\\nTimeoutStopSec=90\\n' | sudo tee /etc/systemd/system/user@.service.d/zz-zerotrust-drive.conf",
                "sudo systemctl daemon-reload",
            ]
        );
        // The upstream default, an override at the unit's own timeout, and
        // an unlimited or unreadable value need no advice.
        for value in ["2min", "1min 30s", "infinity", "", "garbage"] {
            let lines = install_on(
                &host,
                &def,
                Path::new("/usr/bin/zdrive"),
                &user_stop_timeout(value),
            )
            .unwrap();
            assert!(
                !lines.iter().any(|line| line.contains("user manager")),
                "{value}: {lines:?}"
            );
        }
    }

