    #[test]
    fn service_systemd_uninstall_keeps_the_template_for_other_instances() {
        let dir = TestDir::new("service-systemd-uninstall");
        let host = host(&dir, Platform::Linux);
        let def = encrypted(&host, Custody::SystemdCreds);
        install_on(&host, &def, Path::new("/usr/bin/zdrive"), &linger("yes")).unwrap();
        let wants = wants_dir(&host);
        std::fs::create_dir_all(&wants).unwrap();
        std::fs::write(wants.join("zerotrust-drive@other.service"), "").unwrap();

        let runner = FakeRunner::succeeding();
        let lines = uninstall_on(&host, "encrypted", false, &runner).unwrap();
        assert_eq!(
            runner.argv(),
            [
                "systemctl --user disable --now zerotrust-drive@encrypted.service",
                "systemctl --user daemon-reload",
            ]
        );
        assert!(!drop_in_dir(&host, "encrypted").exists());
        assert!(template_path(&host).exists(), "another instance uses it");
        assert!(lines[0].starts_with("stopped and disabled"));

        std::fs::remove_file(wants.join("zerotrust-drive@other.service")).unwrap();
        let missing = FakeRunner::new(|argv, _| {
            if argv.contains("disable") {
                exit(
                    1,
                    "",
                    "Failed to disable unit: Unit file zerotrust-drive@encrypted.service does not exist.",
                )
            } else {
                ok("")
            }
        });
        let lines = uninstall_on(&host, "encrypted", false, &missing).unwrap();
        assert!(lines[0].contains("was not installed"), "{lines:?}");
        assert!(
            !template_path(&host).exists(),
            "the last instance removes it"
        );

        let broken = FakeRunner::new(|_, _| exit(1, "", "Failed to connect to bus"));
        assert!(uninstall_on(&host, "encrypted", false, &broken).is_err());
    }

