pub(crate) const TEMPLATE_NAME: &str = "zerotrust-drive@.service";
const DROP_IN_NAME: &str = "zdrive.conf";
const SYSTEMCTL: &str = "systemctl";
const LOGINCTL: &str = "loginctl";
const STATUS_PROPERTIES: &str = "ActiveState,SubState,MainPID,ExecMainStatus,NRestarts";

pub(crate) fn unit_name(name: &str) -> String {
    format!("zerotrust-drive@{name}.service")
}

pub(crate) fn template_path(host: &Host) -> PathBuf {
    host.systemd_user_dir.join(TEMPLATE_NAME)
}

pub(crate) fn drop_in_dir(host: &Host, name: &str) -> PathBuf {
    host.systemd_user_dir.join(format!("{}.d", unit_name(name)))
}

pub(crate) fn drop_in_path(host: &Host, name: &str) -> PathBuf {
    drop_in_dir(host, name).join(DROP_IN_NAME)
}

fn wants_dir(host: &Host) -> PathBuf {
    host.systemd_user_dir.join("default.target.wants")
}

/// Escapes systemd's `%` specifiers.
fn escape_specifiers(text: &str) -> String {
    text.replace('%', "%%")
}

/// One word of an `ExecStart=` command line.
fn exec_word(word: &str) -> String {
    let escaped = escape_specifiers(word).replace('$', "$$");
    if escaped
        .chars()
        .any(|character| character.is_whitespace() || matches!(character, '"' | '\'' | '\\'))
    {
        format!("\"{}\"", escaped.replace('\\', "\\\\").replace('"', "\\\""))
    } else {
        escaped
    }
}

/// The template unit shared by all instances.
pub(crate) fn template(binary: &str) -> String {
    format!(
        "# Generated by `zdrive service install`; it overwrites this file.
# Instance %i runs the definition
# $XDG_CONFIG_HOME/zerotrust-drive/services/%i.json.
[Unit]
Description=ZeroTrust Drive %i
After=network-online.target
Wants=network-online.target

[Service]
Type=notify
NotifyAccess=main
ExecStart={} service run %i
Restart=on-failure
RestartSec=10s
# 78 (EX_CONFIG) is a refusal: the cause persists until the operator acts,
# and `zdrive service install` starts the instance again.
RestartPreventExitStatus=78
# Before the mount is ready, the first start may pull a whole remote.
TimeoutStartSec=infinity
TimeoutStopSec={STOP_TIMEOUT_SECS}
KillSignal=SIGTERM
# NoNewPrivileges= is deliberately absent: mounting and unmounting go
# through the setuid fusermount3 helper, which needs privilege escalation.

[Install]
WantedBy=default.target
",
        exec_word(binary)
    )
}

/// Whether an installed template differs from the one this zdrive writes,
/// apart from the binary path: an older zdrive generated it.
pub(crate) fn outdated(installed: &str) -> bool {
    fn normalized(text: &str) -> Vec<&str> {
        text.lines()
            .map(|line| {
                if line.starts_with("ExecStart=") {
                    "ExecStart="
                } else {
                    line
                }
            })
            .collect()
    }
    normalized(installed) != normalized(&template("zdrive"))
}

/// The per-instance drop-in, or `None` when the instance needs none.
pub(crate) fn drop_in(host: &Host, def: &Definition) -> Result<Option<String>, String> {
    let mut settings = Vec::new();
    if let Instance::Encrypted {
        custody: Custody::SystemdCreds,
        ..
    } = &def.instance
    {
        let credential = credential_path(&host.paths, &def.name);
        let text = credential
            .to_str()
            .ok_or_else(|| format!("{} is not valid UTF-8", credential.display()))?;
        if text
            .chars()
            .any(|character| character.is_whitespace() || character.is_control())
        {
            return Err(format!(
                "the credential path {text:?} must not contain whitespace; set XDG_CONFIG_HOME to a path without spaces"
            ));
        }
        settings.push(format!(
            "LoadCredentialEncrypted={CREDENTIAL_NAME}:{}",
            escape_specifiers(text)
        ));
    }
    for (key, value) in &host.xdg_environment {
        let assignment = escape_specifiers(&format!("{key}={value}"))
            .replace('\\', "\\\\")
            .replace('"', "\\\"");
        settings.push(format!("Environment=\"{assignment}\""));
    }
    if settings.is_empty() {
        return Ok(None);
    }
    Ok(Some(format!(
        "# Generated by `zdrive service install` for instance {}; it overwrites this file.\n[Service]\n{}\n",
        def.name,
        settings.join("\n")
    )))
}

fn systemctl(args: &[&str]) -> (String, Vec<std::ffi::OsString>) {
    let mut all = vec!["--user"];
    all.extend_from_slice(args);
    (SYSTEMCTL.to_string(), os_args(all))
}

fn remove_empty_dir(dir: &Path) -> Result<(), String> {
    match std::fs::remove_dir(dir) {
        Ok(()) => Ok(()),
        Err(error)
            if matches!(
                error.kind(),
                std::io::ErrorKind::NotFound | std::io::ErrorKind::DirectoryNotEmpty
            ) =>
        {
            Ok(())
        }
        Err(error) => Err(format!("cannot remove {}: {error}", dir.display())),
    }
}

pub(crate) fn install(
    host: &Host,
    def: &Definition,
    binary: &str,
    runner: &dyn Runner,
) -> Result<Vec<String>, String> {
    let name = &def.name;
    let unit = unit_name(name);
    std::fs::create_dir_all(&host.systemd_user_dir)
        .map_err(|error| format!("cannot create {}: {error}", host.systemd_user_dir.display()))?;
    let template_file = template_path(host);
    write_public_file(&template_file, template(binary).as_bytes())?;
    let mut lines = vec![format!("wrote {}", template_file.display())];
    let drop_in_file = drop_in_path(host, name);
    match drop_in(host, def)? {
        Some(text) => {
            let dir = drop_in_dir(host, name);
            std::fs::create_dir_all(&dir)
                .map_err(|error| format!("cannot create {}: {error}", dir.display()))?;
            write_public_file(&drop_in_file, text.as_bytes())?;
            lines.push(format!("wrote {}", drop_in_file.display()));
        }
        None => {
            remove_if_present(&drop_in_file)?;
            remove_empty_dir(&drop_in_dir(host, name))?;
        }
    }
    for args in [
        &["daemon-reload"][..],
        // Applies a changed definition or binary to a running instance;
        // `enable --now` alone leaves it running unchanged.
        &["try-restart", "--no-block", unit.as_str()],
        // --no-block: the first start may pull a whole remote first.
        &["enable", "--now", "--no-block", unit.as_str()],
    ] {
        let (program, args) = systemctl(args);
        run_checked(runner, &program, &args, None)?;
    }
    lines.push(format!(
        "enabled and started {unit}; log: journalctl --user -u {unit}"
    ));
    // Without linger the user manager, and with it the instance, runs only
    // while the user is logged in.
    let user = &host.user;
    let enable = os_args(["--no-ask-password", "enable-linger", user.as_str()]);
    let enabled = run_command(runner, LOGINCTL, &enable, None).and_then(|output| {
        if output.success() {
            Ok(())
        } else {
            Err(failure(LOGINCTL, &enable, &output))
        }
    });
    match (enabled, linger_of(runner, user)) {
        (_, Some(true)) => lines.push(format!(
            "linger is enabled for {user}: {unit} starts at boot without a login"
        )),
        (result, _) => {
            let reason = result
                .err()
                .unwrap_or_else(|| "Linger is still off".to_string());
            lines.push(format!(
                "could not enable linger ({reason}); {unit} runs only while {user} is logged in. To start it at boot, run:"
            ));
            lines.push(format!("sudo loginctl enable-linger {user}"));
        }
    }
    if let Some(limit) = short_user_stop_timeout(runner, host.uid) {
        lines.extend(user_stop_timeout_advice(limit));
    }
    Ok(lines)
}

/// The system manager's stop timeout for the user's manager, `user@UID.service`,
/// in milliseconds; `None` when unknown or unlimited. At shutdown, and at
/// logout without linger, it bounds every user unit's stop, whatever the
/// unit's own `TimeoutStopSec=`. Ubuntu's systemd package lowers it to 5 s.
pub(crate) fn user_stop_timeout_ms(runner: &dyn Runner, uid: u32) -> Option<u64> {
    let unit = format!("user@{uid}.service");
    let output = runner
        .run(
            SYSTEMCTL,
            &os_args(["show", unit.as_str(), "-p", "TimeoutStopUSec"]),
            None,
        )
        .ok()?;
    if !output.success() {
        return None;
    }
    parse_timespan_ms(parse_properties(&output.stdout_text()).get("TimeoutStopUSec")?)
}

/// The user manager's stop timeout when it is shorter than the instance's own.
pub(crate) fn short_user_stop_timeout(runner: &dyn Runner, uid: u32) -> Option<u64> {
    user_stop_timeout_ms(runner, uid).filter(|&ms| ms < STOP_TIMEOUT_SECS * 1000)
}

/// What a short user-manager stop timeout means, and the opt-in remedy.
pub(crate) fn user_stop_timeout_advice(limit_ms: u64) -> Vec<String> {
    vec![
        format!(
            "at shutdown this system stops your user manager after {} (user@.service TimeoutStopSec), so a final upload still running then is cut short: the drive is unmounted and flushed locally first, and the next start uploads the rest. To give it the instance's {STOP_TIMEOUT_SECS} s, run:",
            human_ms(limit_ms)
        ),
        "sudo mkdir -p /etc/systemd/system/user@.service.d".to_string(),
        format!(
            "printf '[Service]\\nTimeoutStopSec={STOP_TIMEOUT_SECS}\\n' | sudo tee /etc/systemd/system/user@.service.d/zz-zerotrust-drive.conf"
        ),
        "sudo systemctl daemon-reload".to_string(),
    ]
}

pub(crate) fn human_ms(ms: u64) -> String {
    if ms.is_multiple_of(1000) {
        format!("{} s", ms / 1000)
    } else {
        format!("{ms} ms")
    }
}

/// A systemd time span as `systemctl show` prints it (`5s`, `1min 30s`,
/// `1.500s`, `infinity`), in milliseconds; `None` for `infinity` or text it
/// does not understand.
fn parse_timespan_ms(text: &str) -> Option<u64> {
    let mut total = 0.0_f64;
    let mut words = 0;
    for word in text.split_whitespace() {
        let split = word
            .find(|character: char| !(character.is_ascii_digit() || character == '.'))
            .filter(|&index| index > 0)?;
        let (number, unit) = word.split_at(split);
        let value: f64 = number.parse().ok()?;
        let unit_ms = match unit {
            "us" | "usec" => 0.001,
            "ms" | "msec" => 1.0,
            "s" | "sec" => 1_000.0,
            "min" | "m" => 60_000.0,
            "h" | "hr" => 3_600_000.0,
            "d" => 86_400_000.0,
            "w" => 604_800_000.0,
            "M" | "month" => 2_629_800_000.0,
            "y" => 31_557_600_000.0,
            _ => return None,
        };
        total += value * unit_ms;
        words += 1;
    }
    (words > 0).then(|| total.round() as u64)
}

fn linger_of(runner: &dyn Runner, user: &str) -> Option<bool> {
    let output = runner
        .run(
            LOGINCTL,
            &os_args(["show-user", user, "-p", "Linger"]),
            None,
        )
        .ok()?;
    if !output.success() {
        return None;
    }
    match parse_properties(&output.stdout_text())
        .get("Linger")
        .copied()
    {
        Some("yes") => Some(true),
        Some("no") => Some(false),
        _ => None,
    }
}

/// Whether the current user's manager survives logout and starts at boot.
pub(crate) fn linger_enabled(runner: &dyn Runner) -> Option<bool> {
    linger_of(runner, &super::user_name(super::current_uid()))
}

/// The major version of the running systemd, from `systemctl --version`.
pub(crate) fn systemd_version(runner: &dyn Runner) -> Option<u32> {
    let output = runner.run(SYSTEMCTL, &os_args(["--version"]), None).ok()?;
    if !output.success() {
        return None;
    }
    parse_version(&output.stdout_text())
}

fn parse_version(text: &str) -> Option<u32> {
    let mut words = text.lines().next()?.split_whitespace();
    if words.next()? != "systemd" {
        return None;
    }
    let version = words.next()?;
    let digits: String = version.chars().take_while(char::is_ascii_digit).collect();
    digits.parse().ok()
}

pub(crate) fn uninstall(
    host: &Host,
    name: &str,
    runner: &dyn Runner,
) -> Result<Vec<String>, String> {
    let unit = unit_name(name);
    let mut lines = Vec::new();
    let (program, args) = systemctl(&["disable", "--now", unit.as_str()]);
    let output = run_command(runner, &program, &args, None)?;
    if output.success() {
        lines.push(format!("stopped and disabled {unit}"));
    } else if output.stderr_text().contains("does not exist")
        || output.stderr_text().contains("not loaded")
    {
        lines.push(format!("{unit} was not installed"));
    } else {
        return Err(failure(&program, &args, &output));
    }
    let drop_in_file = drop_in_path(host, name);
    if remove_if_present(&drop_in_file)? {
        lines.push(format!("deleted {}", drop_in_file.display()));
    }
    remove_empty_dir(&drop_in_dir(host, name))?;
    let others = std::fs::read_dir(wants_dir(host))
        .map(|entries| {
            entries.filter_map(Result::ok).any(|entry| {
                let file_name = entry.file_name();
                let file_name = file_name.to_string_lossy();
                file_name.starts_with("zerotrust-drive@")
                    && file_name.ends_with(".service")
                    && file_name != unit
            })
        })
        .unwrap_or(false);
    let template_file = template_path(host);
    if !others && remove_if_present(&template_file)? {
        lines.push(format!("deleted {}", template_file.display()));
    }
    let (program, args) = systemctl(&["daemon-reload"]);
    run_checked(runner, &program, &args, None)?;
    Ok(lines)
}

/// `Key=Value` lines of `systemctl show` and `loginctl show-user`.
fn parse_properties(text: &str) -> HashMap<&str, &str> {
    text.lines()
        .filter_map(|line| line.split_once('='))
        .map(|(key, value)| (key.trim(), value.trim()))
        .collect()
}

pub(crate) fn status(
    host: &Host,
    name: &str,
    runner: &dyn Runner,
) -> Result<ServiceStatus, String> {
    let unit = unit_name(name);
    let (program, args) = systemctl(&["show", unit.as_str(), "-p", STATUS_PROPERTIES]);
    let output = run_checked(runner, &program, &args, None)?;
    let text = output.stdout_text();
    let properties = parse_properties(&text);
    let active = properties.get("ActiveState").copied().unwrap_or("unknown");
    let sub = properties.get("SubState").copied().unwrap_or("unknown");
    let outdated =
        std::fs::read_to_string(template_path(host)).is_ok_and(|installed| outdated(&installed));
    Ok(ServiceStatus {
        name: name.to_string(),
        installed: std::fs::symlink_metadata(wants_dir(host).join(&unit)).is_ok(),
        running: active == "active" && sub == "running",
        state: format!("{active} ({sub})"),
        pid: properties
            .get("MainPID")
            .and_then(|pid| pid.parse::<u32>().ok())
            .filter(|&pid| pid != 0),
        last_exit_status: properties
            .get("ExecMainStatus")
            .and_then(|status| status.parse().ok()),
        runs: None,
        restarts: properties
            .get("NRestarts")
            .and_then(|restarts| restarts.parse().ok()),
        outdated,
        refusal: None,
    })
}

