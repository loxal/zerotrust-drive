    #[test]
    fn service_systemd_status_parses_systemctl_show() {
        let dir = TestDir::new("service-systemd-status");
        let host = host(&dir, Platform::Linux);
        let runner = FakeRunner::new(|_, _| {
            ok(
                "ActiveState=active\nSubState=running\nMainPID=1234\nExecMainStatus=0\nNRestarts=2\n",
            )
        });
        let status = status_on(&host, "encrypted", &runner).unwrap();
        assert_eq!(
            runner.argv(),
            [
                "systemctl --user show zerotrust-drive@encrypted.service -p ActiveState,SubState,MainPID,ExecMainStatus,NRestarts"
            ]
        );
        assert_eq!(
            status,
            ServiceStatus {
                name: "encrypted".to_string(),
                installed: false,
                running: true,
                state: "active (running)".to_string(),
                pid: Some(1234),
                last_exit_status: Some(0),
                runs: None,
                restarts: Some(2),
                outdated: false,
                refusal: None,
            }
        );
        let wants = wants_dir(&host);
        std::fs::create_dir_all(&wants).unwrap();
        std::fs::write(wants.join("zerotrust-drive@encrypted.service"), "").unwrap();
        let failed = FakeRunner::new(|_, _| {
            ok("ActiveState=failed\nSubState=failed\nMainPID=0\nExecMainStatus=1\nNRestarts=5\n")
        });
        let status = status_on(&host, "encrypted", &failed).unwrap();
        assert!(status.installed);
        assert!(!status.running);
        assert_eq!(status.pid, None);
        assert_eq!(status.state, "failed (failed)");
        assert_eq!(status.last_exit_status, Some(1));
    }

